export const DICT: Record<Lang, Record<string, string>> = { zh, en }

/** 服务端消息原样显示, 前端键名翻成人话 (两者共用一个字段, 靠查表区分). */
export function humanize(langValue: Lang, text: string): string {
  // 客户端拦截会把多条问题用 ' · ' 拼起来, 逐条翻再拼回, 否则整串查不到键只能露出原始 key。
  return text
    .split(' · ')
    .map((part) => {
      const [head, ...rest] = part.split(': ')
      const translated = DICT[langValue][head] ?? DICT.zh[head]
      if (!translated) return part
      return rest.length ? `${translated}: ${rest.join(': ')}` : translated
    })
    .join(' · ')
}
